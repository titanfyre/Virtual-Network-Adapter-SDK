#pragma once
#ifdef _KERNEL_MODE
#include <ntddk.h>
#else
#include <windows.h>
#include <winioctl.h>
#endif
#define VN_VERSION 1u
#define VN_MAX_FRAME 1514u
#define VN_RING_CAPACITY 64u
#define VN_IOCTL_STATUS CTL_CODE(FILE_DEVICE_NETWORK,0x801,METHOD_BUFFERED,FILE_READ_ACCESS)
#define VN_IOCTL_CONNECT CTL_CODE(FILE_DEVICE_NETWORK,0x802,METHOD_BUFFERED,FILE_READ_ACCESS|FILE_WRITE_ACCESS)
#define VN_IOCTL_DISCONNECT CTL_CODE(FILE_DEVICE_NETWORK,0x803,METHOD_BUFFERED,FILE_READ_ACCESS|FILE_WRITE_ACCESS)
#define VN_IOCTL_RECEIVE CTL_CODE(FILE_DEVICE_NETWORK,0x804,METHOD_BUFFERED,FILE_READ_ACCESS|FILE_WRITE_ACCESS)
#define VN_IOCTL_SEND CTL_CODE(FILE_DEVICE_NETWORK,0x805,METHOD_BUFFERED,FILE_READ_ACCESS|FILE_WRITE_ACCESS)
#define VN_IOCTL_CHALLENGE CTL_CODE(FILE_DEVICE_NETWORK,0x806,METHOD_BUFFERED,FILE_READ_ACCESS|FILE_WRITE_ACCESS)
#define VN_IOCTL_AUTHORIZE CTL_CODE(FILE_DEVICE_NETWORK,0x807,METHOD_BUFFERED,FILE_READ_ACCESS|FILE_WRITE_ACCESS)
typedef struct VN_STATE {
    ULONG version,size,running,connected,queued,capacity,max_frame,reserved;
    UCHAR mac[6]; UCHAR padding[2];
    ULONGLONG transmitted,received,dropped;
} VN_STATE;
typedef struct VN_FRAME { ULONG length; UCHAR data[VN_MAX_FRAME]; } VN_FRAME;
#ifdef __cplusplus
static_assert(sizeof(VN_STATE)==64,"ABI");
static_assert(sizeof(VN_FRAME)==1520,"ABI");
#endif
